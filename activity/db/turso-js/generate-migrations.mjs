// Embeds ../migrations/V*.sql into migrations.js, as activities cannot read files.
// Usage: node generate-migrations.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../migrations/', import.meta.url);
const target = new URL('migrations.js', import.meta.url);

export function generate() {
    const migrations = readdirSync(dir).sort().map((file) => {
        const [, version, name] = file.match(/^V(\d+)__(\w+)\.sql$/) ?? [];
        if (!version) throw new Error(`unexpected migration file name ${file}`);
        return { version: Number(version), name, sql: readFileSync(new URL(file, dir), 'utf8') };
    }).sort((a, b) => a.version - b.version);
    return '// Generated by generate-migrations.mjs from ../migrations, do not edit.\n' +
        `export const MIGRATIONS = ${JSON.stringify(migrations, null, 4)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    if (process.argv[2] === '--check') {
        if (readFileSync(target, 'utf8') !== generate()) throw new Error('migrations.js is out of date');
    } else {
        writeFileSync(target, generate());
    }
}
